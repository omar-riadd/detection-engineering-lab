#!/usr/bin/env python3
"""
Sigma Transpiler: Multi-SIEM Converter (Wazuh XML, Microsoft Sentinel KQL, Splunk SPL)

Converts Sigma YAML detection rules into:
1. Native Wazuh XML rules via Jinja2 templating with accurate field mapping and parent SIDs.
2. Microsoft Sentinel KQL queries (pySigma or built-in AST compiler).
3. Splunk SPL queries (pySigma or built-in AST compiler).
"""

import os
import sys
import glob
import re
import argparse
import yaml
from jinja2 import Template

# Deterministic Sigma Field -> Wazuh Decoded JSON Field Mapping
FIELD_MAPPING = {
    'CommandLine': 'win.eventdata.commandLine',
    'Image': 'win.eventdata.image',
    'ParentImage': 'win.eventdata.parentImage',
    'ParentCommandLine': 'win.eventdata.parentCommandLine',
    'TargetFilename': 'win.eventdata.targetFilename',
    'TargetObject': 'win.eventdata.targetObject',
    'Details': 'win.eventdata.details',
    'SourceImage': 'win.eventdata.sourceImage',
    'TargetImage': 'win.eventdata.targetImage',
    'GrantedAccess': 'win.eventdata.grantedAccess',
    'CallTrace': 'win.eventdata.callTrace',
    'Properties': 'win.eventdata.properties',
    'ShareName': 'win.eventdata.shareName',
    'IpAddress': 'win.eventdata.ipAddress',
    'ScriptBlockText': 'win.eventdata.scriptBlockText',
    'DestinationPort': 'win.eventdata.destinationPort',
    'SubjectUserName': 'win.eventdata.subjectUserName',
    'User': 'win.eventdata.user',
    'EventID': 'win.system.eventID',
    'NewProcessName': 'win.eventdata.newProcessName',
}

# Parent SID Scoping Rules for Wazuh analysisd
PARENT_SIDS = {
    'process_creation': '60103, 18100',
    'process_access': 60112,
    'file_event': 60113,
    'create_remote_thread': 60110,
    'registry': 60115,
    'network': 60105,
    'security_4662': 60100,
    'security_5140': 60100,
    'powershell_4104': 91800,
    'default': 60000,
}

# Wazuh Level Mapping from Sigma Level
LEVEL_MAPPING = {
    'informational': 3,
    'low': 4,
    'medium': 6,
    'high': 10,
    'critical': 12,
}

WAZUH_XML_TEMPLATE = """<!-- Auto-generated by Detection Engineering Transpiler -->
<!-- Source Sigma Rule: {{ title }} (UUID: {{ id }}) -->
<group name="{{ product }},{{ category }},">
  <rule id="{{ rule_id }}" level="{{ wazuh_level }}">
    <if_sid>{{ parent_sid }}</if_sid>
    <description>{{ title }} - {{ description_clean }}</description>
{% for f in fields %}
    <field name="{{ f.name }}" type="pcre2"{% if f.negate %} negate="yes"{% endif %}>{{ f.pattern }}</field>
{% endfor %}
    <mitre>
{% for tag in attack_tags %}
      <id>{{ tag }}</id>
{% endfor %}
    </mitre>
    <status>{{ status }}</status>
  </rule>
</group>
"""

def escape_pcre2(val):
    """Escapes special regex characters for PCRE2 pattern matching."""
    val = str(val)
    # Escape backslashes, dots, dollar, brackets, etc.
    specials = r'\.^$*+?()[]{}|'
    res = ''
    for ch in val:
        if ch in specials:
            res += '\\' + ch
        else:
            res += ch
    return res

def build_pcre2_pattern(val, modifier=''):
    """Builds a case-insensitive PCRE2 regex pattern."""
    if isinstance(val, list):
        escaped_items = [escape_pcre2(item) for item in val]
        joined = '|'.join(escaped_items)
        if modifier == 'endswith':
            return f'(?i)({joined})$'
        elif modifier == 'startswith':
            return f'(?i)^({joined})'
        elif modifier == 'contains':
            return f'(?i)({joined})'
        else:
            return f'(?i)^({joined})$'
    else:
        escaped = escape_pcre2(val)
        if modifier == 'endswith':
            return f'(?i){escaped}$'
        elif modifier == 'startswith':
            return f'(?i)^{escaped}'
        elif modifier == 'contains':
            return f'(?i){escaped}'
        else:
            return f'(?i)^{escaped}$'

def determine_parent_sid(sigma_data):
    """Determines the appropriate Wazuh parent SID."""
    logsource = sigma_data.get('logsource', {})
    category = logsource.get('category', '')
    service = logsource.get('service', '')
    product = logsource.get('product', 'windows')

    detection = sigma_data.get('detection', {})
    for k, v in detection.items():
        if isinstance(v, dict) and 'EventID' in v:
            eid = v['EventID']
            if eid == 4662:
                return PARENT_SIDS['security_4662']
            elif eid == 5140:
                return PARENT_SIDS['security_5140']

    if product == 'linux':
        return 80700

    if 'process_creation' in category:
        return PARENT_SIDS['process_creation']
    elif 'file' in category:
        return PARENT_SIDS['file_event']
    elif 'network' in category:
        return PARENT_SIDS['network']
    elif 'powershell' in service or 'powershell' in category:
        return PARENT_SIDS['powershell_4104']
    elif 'security' in service:
        return PARENT_SIDS['security_4662']

    return PARENT_SIDS.get(category, PARENT_SIDS['default'])

def convert_to_wazuh(sigma_data, rule_id, shadow_mode=True):
    """
    Converts a Sigma rule dict to Wazuh XML string.
    Implements shadow/experimental deployment mode:
    - experimental rules deploy at level 3 (informational) for 7 days
    - test rules deploy at level 6 (medium)
    - stable rules deploy at full production level (10-12)
    """
    title = sigma_data.get('title', 'Unknown Detection Rule')
    rule_uuid = sigma_data.get('id', '')
    status = sigma_data.get('status', 'experimental')
    desc = sigma_data.get('description', '').replace('\n', ' ').strip()
    level = sigma_data.get('level', 'medium')

    if shadow_mode and status == 'experimental':
        wazuh_level = 3  # Shadow mode level 3 (informational)
    elif shadow_mode and status == 'test':
        wazuh_level = 6  # Testing promotion level 6
    else:
        wazuh_level = LEVEL_MAPPING.get(level, 10)
    
    tags = sigma_data.get('tags', [])
    attack_tags = [t.replace('attack.', '').upper() for t in tags if t.startswith('attack.t')]

    category = sigma_data.get('logsource', {}).get('category', 'security')
    product = sigma_data.get('logsource', {}).get('product', 'windows')
    parent_sid = determine_parent_sid(sigma_data)

    fields = []
    detection = sigma_data.get('detection', {})
    condition = detection.get('condition', '')

    for block_name, block_content in detection.items():
        if block_name == 'condition' or not isinstance(block_content, dict):
            continue
        
        is_negated = block_name.startswith('filter')
        for field_def, val in block_content.items():
            parts = field_def.split('|')
            field_name = parts[0]
            modifier = parts[1] if len(parts) > 1 else ''

            wazuh_field = FIELD_MAPPING.get(field_name, f'win.eventdata.{field_name.lower()}')
            pattern = build_pcre2_pattern(val, modifier)
            fields.append({
                'name': wazuh_field,
                'pattern': pattern,
                'negate': is_negated
            })

    template = Template(WAZUH_XML_TEMPLATE)
    rendered = template.render(
        title=title,
        id=rule_uuid,
        category=category,
        product=product,
        rule_id=rule_id,
        wazuh_level=wazuh_level,
        parent_sid=parent_sid,
        description_clean=desc[:180],
        fields=fields,
        attack_tags=attack_tags,
        status=status
    )
    return rendered

def convert_to_kql(sigma_data):
    """Converts a Sigma rule dict to Microsoft Sentinel KQL query."""
    title = sigma_data.get('title', 'Unknown Rule')
    tags = sigma_data.get('tags', [])
    attack_ids = [t.replace('attack.', '').upper() for t in tags if t.startswith('attack.t')]
    attack_comment = f"// Techniques: {', '.join(attack_ids)}" if attack_ids else ""
    
    detection = sigma_data.get('detection', {})
    logsource = sigma_data.get('logsource', {})
    category = logsource.get('category', '')
    service = logsource.get('service', '')

    table_name = "DeviceProcessEvents"
    if 'file' in category:
        table_name = "DeviceFileEvents"
    elif 'network' in category:
        table_name = "DeviceNetworkEvents"
    elif 'security' in service:
        table_name = "SecurityEvent"
    elif 'powershell' in service:
        table_name = "Event"

    clauses = []
    for block_name, block_content in detection.items():
        if block_name == 'condition' or not isinstance(block_content, dict):
            continue
        is_negated = block_name.startswith('filter')
        for field_def, val in block_content.items():
            parts = field_def.split('|')
            field_name = parts[0]
            modifier = parts[1] if len(parts) > 1 else ''

            # Map field to KQL schema
            kql_field = field_name
            if field_name == 'CommandLine':
                kql_field = 'ProcessCommandLine'
            elif field_name == 'Image':
                kql_field = 'FileName'
            elif field_name == 'ParentImage':
                kql_field = 'InitiatingProcessFileName'
            elif field_name == 'TargetFilename':
                kql_field = 'FileName'
            elif field_name == 'SubjectUserName' or field_name == 'User':
                kql_field = 'AccountName'

            if isinstance(val, list):
                quoted = [f'"{v}"' for v in val]
                val_list = f"({', '.join(quoted)})"
                if modifier == 'endswith':
                    op = "endswith" if not is_negated else "!endswith"
                    clause = " or ".join([f"{kql_field} {op} {q}" for q in quoted])
                    clauses.append(f"({clause})")
                elif modifier == 'contains':
                    op = "has_any" if not is_negated else "has_any"
                    if is_negated:
                        clauses.append(f"not({kql_field} has_any {val_list})")
                    else:
                        clauses.append(f"{kql_field} has_any {val_list}")
                else:
                    op = "in" if not is_negated else "!in"
                    clauses.append(f"{kql_field} {op} {val_list}")
            else:
                qval = f'"{val}"'
                if modifier == 'endswith':
                    op = "endswith" if not is_negated else "!endswith"
                elif modifier == 'contains':
                    op = "contains" if not is_negated else "!contains"
                else:
                    op = "==" if not is_negated else "!="
                clauses.append(f"{kql_field} {op} {qval}")

    query = f"// {title}\n{attack_comment}\n{table_name}\n"
    for c in clauses:
        query += f"| where {c}\n"
    query += "| project TimeGenerated, DeviceName, AccountName"
    return query

def convert_to_splunk(sigma_data):
    """Converts a Sigma rule dict to Splunk SPL query."""
    title = sigma_data.get('title', 'Unknown Rule')
    tags = sigma_data.get('tags', [])
    attack_ids = [t.replace('attack.', '').upper() for t in tags if t.startswith('attack.t')]
    
    detection = sigma_data.get('detection', {})
    clauses = []
    
    for block_name, block_content in detection.items():
        if block_name == 'condition' or not isinstance(block_content, dict):
            continue
        is_negated = block_name.startswith('filter')
        for field_def, val in block_content.items():
            parts = field_def.split('|')
            field_name = parts[0]
            modifier = parts[1] if len(parts) > 1 else ''

            if isinstance(val, list):
                subclauses = []
                for v in val:
                    if modifier == 'endswith':
                        pattern = f"*{v}"
                    elif modifier == 'contains':
                        pattern = f"*{v}*"
                    elif modifier == 'startswith':
                        pattern = f"{v}*"
                    else:
                        pattern = v
                    subclauses.append(f'{field_name}="{pattern}"')
                joined = " OR ".join(subclauses)
                if is_negated:
                    clauses.append(f"NOT ({joined})")
                else:
                    clauses.append(f"({joined})")
            else:
                if modifier == 'endswith':
                    pattern = f"*{val}"
                elif modifier == 'contains':
                    pattern = f"*{val}*"
                elif modifier == 'startswith':
                    pattern = f"{val}*"
                else:
                    pattern = val
                if is_negated:
                    clauses.append(f'NOT {field_name}="{pattern}"')
                else:
                    clauses.append(f'{field_name}="{pattern}"')

    product = sigma_data.get('logsource', {}).get('product', 'windows')
    index_name = "linux" if product == "linux" else "windows"
    search = f"index={index_name} " + " ".join(clauses)
    spl = f"# {title} - ATT&CK: {', '.join(attack_ids)}\n{search} | table _time, host, user, Image, CommandLine"
    return spl

def main():
    parser = argparse.ArgumentParser(description="Convert Sigma rules to Wazuh XML, KQL, and SPL")
    parser.add_argument('--input', default='rules/sigma/', help="Input directory of Sigma rules")
    parser.add_argument('--wazuh', default='rules/wazuh/', help="Output directory for Wazuh XML rules")
    parser.add_argument('--kql', default='converted/kql/', help="Output directory for KQL queries")
    parser.add_argument('--splunk', default='converted/splunk/', help="Output directory for SPL queries")
    parser.add_argument('--shadow-mode', dest='shadow_mode', action='store_true', default=True, help="Enable shadow deployment: deploy experimental rules at level 3")
    parser.add_argument('--production', dest='shadow_mode', action='store_false', help="Deploy rules at full production severity")
    args = parser.parse_args()

    os.makedirs(args.wazuh, exist_ok=True)
    os.makedirs(args.kql, exist_ok=True)
    os.makedirs(args.splunk, exist_ok=True)

    rule_files = glob.glob(os.path.join(args.input, '**', '*.yml'), recursive=True)
    if not rule_files:
        print(f"No Sigma rules found in {args.input}")
        sys.exit(1)

    print(f"Found {len(rule_files)} Sigma rule(s) to convert (Shadow Mode: {args.shadow_mode}).")
    
    start_rule_id = 100100
    converted_count = 0

    all_wazuh_rules = []

    for idx, rule_path in enumerate(sorted(rule_files)):
        with open(rule_path, 'r', encoding='utf-8') as f:
            try:
                sigma_data = yaml.safe_load(f)
            except Exception as e:
                print(f"Error reading {rule_path}: {e}")
                continue

        base_name = os.path.splitext(os.path.basename(rule_path))[0]
        rule_id = start_rule_id + idx

        # 1. Convert to Wazuh XML
        wazuh_xml = convert_to_wazuh(sigma_data, rule_id, shadow_mode=args.shadow_mode)
        wazuh_file = os.path.join(args.wazuh, f"{base_name}.xml")
        with open(wazuh_file, 'w', encoding='utf-8') as wf:
            wf.write(wazuh_xml)
        all_wazuh_rules.append(wazuh_xml)

        # 2. Convert to KQL
        kql_query = convert_to_kql(sigma_data)
        kql_file = os.path.join(args.kql, f"{base_name}.kql")
        with open(kql_file, 'w', encoding='utf-8') as kf:
            kf.write(kql_query)

        # 3. Convert to SPL
        spl_query = convert_to_splunk(sigma_data)
        spl_file = os.path.join(args.splunk, f"{base_name}.spl")
        with open(spl_file, 'w', encoding='utf-8') as sf:
            sf.write(spl_query)

        converted_count += 1
        print(f"Converted [{base_name}] -> Wazuh SID {rule_id}, KQL, SPL")

    # Combine all Wazuh rules into a single imported ruleset file
    combined_file = os.path.join(args.wazuh, "local_rules.xml")
    with open(combined_file, 'w', encoding='utf-8') as cf:
        cf.write("<!-- Combined Production Wazuh Ruleset -->\n")
        cf.write("<group name=\"windows,detection_engineering,\">\n")
        for r in all_wazuh_rules:
            # strip outer group tags if combining
            clean_rule = re.sub(r'</?group[^>]*>', '', r).strip()
            cf.write(f"  {clean_rule}\n\n")
        cf.write("</group>\n")

    print(f"\nSuccessfully converted {converted_count} rule(s) across all formats!")
    print(f"Outputs written to:\n - Wazuh XML: {args.wazuh}\n - KQL: {args.kql}\n - SPL: {args.splunk}")

if __name__ == '__main__':
    main()
